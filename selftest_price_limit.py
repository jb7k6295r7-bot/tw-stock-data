#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""`price_limit` 的自測。**不連網、不讀檔。**

⭐ 這一支的主角不是「算得對不對」，是**年代切分真的有作用**：
⛔ 一條把 7% 年代用 10% 去量的閘門，在紙上跟對的一模一樣——它只是**少抓**。
⇒ 所以每一格官方數字都配一條反向斷言：**用寫死的 10% 去算，那一格就會錯**。
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import price_limit as P                                        # noqa: E402

OK = FAIL = 0


def ck(name, cond, hint=""):
    global OK, FAIL
    if cond:
        OK += 1
        print(f"  ok   {name}")
    else:
        FAIL += 1
        print(f"  ✗    {name}" + (f"｜{hint}" if hint else ""))


def _flat10_up(ref):
    """⛔ 「沒有年代切分」的那一版，只在反向斷言裡用。"""
    return P._round_to_tick(ref * 1.10, True)


def main():
    print("=" * 64)
    print("price_limit：交易所的漲跌停（不連網）")
    print("=" * 64)

    # ── ① 年代 ──────────────────────────────────────────────
    print("\n── ① 2015-06-01 由 7% 放寬為 10% ──")
    ck("放寬日**當天**就是 10%", P.cap("2015-06-01") == 0.10)
    ck("⭐ 放寬日**前一個交易日**還是 7%（⛔ 邊界要釘在日期上，不是年份）",
       P.cap("2015-05-29") == 0.07, f"得到 {P.cap('2015-05-29')}")
    ck("放寬之後都是 10%", P.cap("2026-09-13") == 0.10)
    ck("放寬很久之前都是 7%", P.cap("2008-01-10") == 0.07)

    # ── ② 升降單位 ─────────────────────────────────────────
    print("\n── ② 升降單位是看**算出來的那個價**落在哪一檔 ──")
    ck("未滿 10 ⇒ 0.01", P.tick(9.99) == 0.01)
    ck("10 ⇒ 0.05（⛔ 邊界是「10 元以上」，不是「超過 10」）", P.tick(10.0) == 0.05)
    ck("未滿 50 ⇒ 0.05", P.tick(49.95) == 0.05)
    ck("50 ⇒ 0.1", P.tick(50.0) == 0.1)
    ck("100 ⇒ 0.5", P.tick(100.0) == 0.5)
    ck("500 ⇒ 1", P.tick(500.0) == 1.0)
    ck("1000 以上 ⇒ 5", P.tick(1234.0) == 5.0)
    # ⭐ 而「看 ref 落在哪一檔」是錯的：ref 49.90 的漲停是 54.89 ⇒ 要用 0.1
    ck("⭐ ref 在 0.05 那一檔、漲停跨進 0.1 那一檔 ⇒ 用**漲停自己**那一檔",
       P.up(49.90, "2026-01-02") == 54.80, f"得到 {P.up(49.90, '2026-01-02')}")

    # ── ③ 官方自己給的漲跌停（TWTAUU）─────────────────────
    #   ⚠ 這三列是 `selftest_reduce.py` 用的同一份官方回應，⛔ 不是我算出來的。
    print("\n── ③ 對官方 TWTAUU 的漲跌停逐位比對 ──")
    ck("⭐ 3040 遠見 2015-01-23 ref 41.28 ⇒ 漲停 44.15（7% era）",
       P.up(41.28, "2015-01-23") == 44.15, f"得到 {P.up(41.28, '2015-01-23')}")
    ck("⭐ 3040 同日 ⇒ 跌停 38.40", P.down(41.28, "2015-01-23") == 38.40,
       f"得到 {P.down(41.28, '2015-01-23')}")
    ck("⭐ 3536 誠創 2015-03-20 ref 13.33 ⇒ 漲停 14.25（7% era）",
       P.up(13.33, "2015-03-20") == 14.25, f"得到 {P.up(13.33, '2015-03-20')}")
    ck("⭐ 2017 官田鋼 2015-12-30 ref 6.17 ⇒ 漲停 6.78（10% era）",
       P.up(6.17, "2015-12-30") == 6.78, f"得到 {P.up(6.17, '2015-12-30')}")
    ck("⭐ 2017 同日 ⇒ 跌停 5.56", P.down(6.17, "2015-12-30") == 5.56,
       f"得到 {P.down(6.17, '2015-12-30')}")

    # ── ④ ⛔ 已知未解：官方那一格跟公式對不上 ───────────────
    print("\n── ④ ⛔ 已知未解的那一格（⚠ 不要為了好看去改公式）──")
    # 官方 3536 2015-03-20 的跌停欄是 **12.15**，公式算出 12.40（差 5 檔）。
    # ⚠ 同一列的漲停、以及另外兩列的四格**全部逐位相同** ⇒ 不是欄位取錯。
    # ⛔ 我不知道成因 ⇒ 就釘住現況：有人日後「修好」它，這一條會講話。
    ck("⛔ 3536 的跌停，公式給 12.40 而官方給 12.15（**已知未解**）",
       P.down(13.33, "2015-03-20") == 12.40,
       f"得到 {P.down(13.33, '2015-03-20')}")

    # ── ⑤ ⭐ 反向：拿掉年代切分，7% 那兩格就錯 ─────────────
    print("\n── ⑤ ⭐ 反向：若寫死 10%，7% 年代那幾格會錯 ──")
    ck("⭐ 寫死 10% ⇒ 3040 的漲停變成 45.40，⛔ 不是官方的 44.15",
       _flat10_up(41.28) != 44.15 and _flat10_up(41.28) == 45.40,
       f"得到 {_flat10_up(41.28)}")
    ck("⭐ 寫死 10% ⇒ 3536 的漲停變成 14.65，⛔ 不是官方的 14.25",
       _flat10_up(13.33) == 14.65, f"得到 {_flat10_up(13.33)}")
    ck("⚠ 而 10% 年代那一格**兩種寫法都對** ⇒ ⛔ 只拿它當錨點等於沒有錨點",
       _flat10_up(6.17) == P.up(6.17, "2015-12-30") == 6.78)

    # ── ⑥ 捨去／進位的方向 ────────────────────────────────
    print("\n── ⑥ 漲停**捨去**、跌停**進位**（⛔ 方向反了會放行） ──")
    ck("⭐ 漲停是捨去：41.28×1.07 = 44.1696 ⇒ 44.15（⛔ 不是 44.20）",
       P.up(41.28, "2015-01-23") == 44.15)
    ck("⭐ 跌停是進位：41.28×0.93 = 38.3904 ⇒ 38.40（⛔ 不是 38.35）",
       P.down(41.28, "2015-01-23") == 38.40)
    # ⚠ 剛好落在檔位上的時候不可以多跳一檔（浮點在這裡最容易出事）
    ck("⭐ 剛好落在檔位上 ⇒ 就是它自己（20.00×1.10 = 22.00）",
       P.up(20.00, "2026-01-02") == 22.00, f"得到 {P.up(20.00, '2026-01-02')}")
    ck("⭐ 剛好落在檔位上（跌停側）⇒ 20.00×0.90 = 18.00",
       P.down(20.00, "2026-01-02") == 18.00, f"得到 {P.down(20.00, '2026-01-02')}")

    # ── ⑦ ⭐ 跌停側**故意不收緊**（有反例）───────────────
    print("\n── ⑦ ⭐ 跌停側的不對稱是故意的（⛔ 不是忘了改）──")
    # ⛔⛔ 3536 那天**跌停鎖死在 12.15**（我方收盤就是 12.15），而公式算 12.40。
    #   ⇒ 拿公式當閘門 ⇒ **誤報一筆**，而它其實證明不了任何因子有錯。
    ck("⛔ 公式的跌停會把 3536 那天判成超出（12.15 < 12.40）",
       P.down(13.33, "2015-03-20") > 12.15)
    ck("⭐ 而閘門用的 `down_observed` 取較寬的那個 ⇒ 12.00 ⇒ **不誤報**",
       P.down_observed(13.33, "2015-03-20") == 12.00,
       f"得到 {P.down_observed(13.33, '2015-03-20')}")
    ck("⭐ ⇒ `within` 放行 3536 那一天（⛔ 這一條就是「誤報 0」的守門員）",
       P.within(12.15, 13.33, "2015-03-20"))
    ck("⚠ 而 10% 年代兩者相同 ⇒ ⛔ 不對稱只存在於 7% 年代",
       P.down_observed(6.17, "2015-12-30") == P.down(6.17, "2015-12-30") == 5.56)

    # ── ⑧ within ─────────────────────────────────────────
    print("\n── ⑧ within：⛔ 餘裕是**相對**的（三點6）──")
    ck("漲停價本身算在內", P.within(44.15, 41.28, "2015-01-23"))
    ck("⭐ 超過漲停一檔就不在內（44.20）", not P.within(44.20, 41.28, "2015-01-23"))
    ck("⭐ 而那一格用 10% 去量就會**靜靜放行** ⇒ 這就是少抓的樣子",
       P.within(44.20, 41.28, "2015-12-30"))
    ck("跌停價本身算在內（⚠ 這裡是 10% 那一版的 37.20）",
       P.within(37.20, 41.28, "2015-01-23"))
    ck("低於它一檔就不在內", not P.within(37.15, 41.28, "2015-01-23"))
    ck("⛔ ref 不合法（0／None）⇒ 不判（回 True），不是崩潰",
       P.within(1.0, 0, "2026-01-02") and P.within(1.0, None, "2026-01-02"))
    # ⭐ 有預設值的參數，一定要有一條**不傳它**的斷言（第七點③）
    ck("⭐ `slack` 不傳 ⇒ 預設 0（⛔ 這條路是 `factor_limit_check` 唯一會走的）",
       not P.within(44.20, 41.28, "2015-01-23"))
    ck("⭐ 而 slack 是相對的：1% 的餘裕讓 44.20 通過（44.15×1.01 = 44.59）",
       P.within(44.20, 41.28, "2015-01-23", slack=0.01))
    # ⛔ 跌停側的 slack 也必須是**相對**的——⚠ 只驗漲停側的話，
    #   把跌停那一半改成絕對值（`- slack`）**一條都不會紅**（實測 M6 全綠）。
    ck("⭐ 跌停側的 slack 也是相對的：37.20×0.99 = 36.83 ⇒ 36.90 通過",
       P.within(36.90, 41.28, "2015-01-23", slack=0.01))
    ck("⛔ 而若它是絕對值（37.20−0.01 = 37.19），36.90 就會被判成超出",
       not P.within(36.90, 41.28, "2015-01-23"))

    # ── ⑨ ETF 的升降單位（⛔ 跟股票不同，只有兩檔）────────
    print("\n── ⑨ ⭐ ETF 的升降單位跟股票不同（官方逐筆數字證實）──")
    ck("⭐ 00939 2026-01-02 ref 14.62 ⇒ 官方漲停 16.08（ETF 檔位 0.01）",
       P.up(14.62, "2026-01-02", etf=True) == 16.08,
       f"得到 {P.up(14.62, '2026-01-02', etf=True)}")
    ck("⛔ 而用股票的 0.05 去算會得到 16.05 ⇒ 差一檔，⚠ 在紙上看不出來",
       P.up(14.62, "2026-01-02") == 16.05)
    ck("⭐ 同日跌停 13.16", P.down(14.62, "2026-01-02", etf=True) == 13.16,
       f"得到 {P.down(14.62, '2026-01-02', etf=True)}")
    ck("ETF 50 元以上換 0.05", P.tick(60.0, etf=True) == 0.05)
    ck("ETF 未滿 50 都是 0.01（⛔ 股票在 10 元就換檔了）",
       P.tick(9.99, etf=True) == P.tick(49.99, etf=True) == 0.01)
    # ⭐ 有預設值的參數，一定要有一條**不傳它**的斷言（第七點③）
    ck("⭐ `etf` 不傳 ⇒ 走股票那張表（⛔ 這是絕大多數呼叫點會走的路）",
       P.tick(20.0) == 0.05 and P.up(41.28, "2015-01-23") == 44.15)

    # ── ⑨.5 ⭐ 誰是「0.01 那一族」——⛔ 量出來的，不是照分類猜的
    print("\n── ⑨.5 ⭐ `is_fine_tick`：拿官方 1,453 筆反推出來的分族 ──")
    ck("⭐ 0050 是 ETF（⛔ 四位純數字 ⇒ 只看位數會漏掉它）", P.is_fine_tick("0050"))
    ck("00939／00714 也是", P.is_fine_tick("00939") and P.is_fine_tick("00714"))
    ck("⭐ 01001T 不動產信託受益證券 ⇒ 0.01", P.is_fine_tick("01001T"))
    ck("⛔ 2330 普通股 ⇒ 股票檔位", not P.is_fine_tick("2330"))
    ck("⛔ 2002A 特別股 ⇒ **股票**檔位（官方 36.10，0.01 會給 36.09）",
       not P.is_fine_tick("2002A"))
    ck("⛔ 910322 TDR ⇒ **股票**檔位（官方 29.10，0.01 會給 29.06）",
       not P.is_fine_tick("910322") and not P.is_fine_tick("911609"))
    # ⭐ 而這幾格是**官方數字**，⛔ 不是我算的
    ck("⭐ 0050 2015-10-26 ref 63.90 ⇒ 官方漲停 70.25（ETF 50 元以上 0.05）",
       P.up(63.90, "2015-10-26", etf=True) == 70.25,
       f"得到 {P.up(63.90, '2015-10-26', etf=True)}")
    ck("⭐ 0051 2015-11-24 ref 24.80 ⇒ 官方漲停 27.28、跌停 22.32（0.01）",
       P.up(24.80, "2015-11-24", etf=True) == 27.28
       and P.down(24.80, "2015-11-24", etf=True) == 22.32)
    ck("⭐ 01001T 2015-05-07 ref 18.38 ⇒ 官方 19.66／17.10（7% 年代＋0.01）",
       P.up(18.38, "2015-05-07", etf=True) == 19.66
       and P.down(18.38, "2015-05-07", etf=True) == 17.10,
       f"得到 {P.up(18.38, '2015-05-07', etf=True)}／"
       f"{P.down(18.38, '2015-05-07', etf=True)}")
    ck("⛔ 而把 01001T 當普通股算就會錯（19.65／16.55）",
       P.up(18.38, "2015-05-07") == 19.65)

    # ── ⑩ 官方怎麼說「無漲跌幅限制」──────────────────
    print("\n── ⑩ ⭐ 官方用 9,999.95／0.01 標「無漲跌幅限制」──")
    ck("⭐ 00714 2020-01-16 的 9,999.95／0.01 ⇒ 無限制",
       P.is_unlimited("9,999.95", "0.01"))
    ck("⛔ 而正常的漲跌停不會被誤判", not P.is_unlimited("22.80", "19.55"))
    ck("⚠ 逗號要吃掉（官方就是帶逗號給的）", P.is_unlimited("9,999.95", "5.00"))
    ck("⛔ 空值／非數字 ⇒ False，不是崩潰（⚠ 舊日檔沒有這兩欄）",
       not P.is_unlimited("", "") and not P.is_unlimited(None, None))
    ck("⭐ 只要有一邊是旗標就算（官方兩邊一起給，⛔ 但不要賭）",
       P.is_unlimited("100.00", "0.01"))

    # ── ⑪ ⛔ 官方的漲停與跌停**基準可以不同** ──────────
    print("\n── ⑪ ⛔ 2353 2015-01-05：漲停與跌停各用不同的基準 ──")
    ck("⭐ 漲停 22.80 是用**減除股利參考價** 21.35 算的",
       P.up(21.35, "2015-01-05") == 22.80, f"得到 {P.up(21.35, '2015-01-05')}")
    ck("⭐ 跌停 19.55 是用**除權息參考價** 21.02 算的",
       P.down(21.02, "2015-01-05") == 19.55, f"得到 {P.down(21.02, '2015-01-05')}")
    ck("⛔ 而拿同一個基準算，兩邊不可能同時對（22.45 ≠ 22.80）",
       P.up(21.02, "2015-01-05") != 22.80)

    print(f"\n[selftest] 通過 {OK}｜失敗 {FAIL}")
    return 1 if FAIL else 0


if __name__ == "__main__":
    sys.exit(main())
