OK = FAIL = 0


def ck(name, cond, hint=""):
    global OK, FAIL
    if cond:
        OK += 1
        print("  ok     " + name)
    else:
        FAIL += 1
        print("  ✗      " + name + ("｜" + hint if hint else ""))


class Quiet(object):
    """把 section 的輸出收起來：這裡要的是回傳值，⛔ 不是好看的報表。"""

    def __enter__(self):
        self._o = sys.stdout
        sys.stdout = self.buf = io.StringIO()
        return self

    def __exit__(self, *a):
        sys.stdout = self._o
        self.text = self.buf.getvalue()
        return False


TMP = os.path.join(HERE, "_selftest_instamt_audit_empty")


def recon(data, feed):
    with Quiet() as q:
        r = A.sec_recon(data, feed, TMP)      # ⚠ 空目錄 ⇒ 不做 market_inst 比對
    return r, q.text


