"""PREREG事件 seq2：由 resultsEvt/ 產 REPORT.md（只讀檔，不重算）。

    cd ~/tw-p17 && ~/tw-p16/.venv/bin/python backtest/researchEvt_report.py
"""
from __future__ import annotations
import json, os
import pandas as pd

OUT = os.path.expanduser("~/tw-p17/backtest/resultsEvt")
ONE = ("**庫藏股**：確認段（2019～2026-08）三種類型、五個視窗，扣成本後對基準② **全部測不出**。"
       "早年段（2005～2011，只上市）只有 20 日兩格過 Bonferroni 門檻：全部 +1.27%、目的 3 +1.92%；相鄰視窗沒過，所以 ⛔ 不寫「穩」。"
       "組合層挑中「全部、抱 120 日」：確認段 +19.11%／−40.24% **不合格**（0050 +29.71%／−33.96%）；"
       "早年段 +9.07%／−53.86% 合格（0050 +4.79%／−55.75%）⇒ 件標籤 **不合格**。"
       "**臺灣50 剔除**：每格不到 100 筆、年均不到 10 件 ⇒ 單筆層與組合層都 **依構造不可判定**，不計 N。")


def P(x, d=2):
    return "—" if x is None or pd.isna(x) else f"{x * 100:+.{d}f}%"


def main():
    S = json.load(open(os.path.join(OUT, "summary.json"), encoding="utf-8"))
    SG = pd.read_csv(os.path.join(OUT, "single.csv")); PC = pd.read_csv(os.path.join(OUT, "port_cells.csv"))
    CK = json.load(open(os.path.join(OUT, "check.json"), encoding="utf-8")) if os.path.exists(os.path.join(OUT, "check.json")) else {}
    pk = S["組合層挑格"]; Z = S["0050"]
    L = []; w = L.append
    w("# PREREG事件 seq2 REPORT（回測 研究事件）\n")
    w("> 回測線，2026-09-28。登錄：台股策略線 事件型兩件 seq2（sha 8eae2968c12438fc，取代 seq1）；裁定 seq259 §四、seq262 §五 發號；N ＋2（庫藏股、臺灣50 組合層各 1 格）。\n")
    w("## 一句話\n")
    w(ONE + "\n")
    w("| 項目 | 確認 2019–2026-08 | 早年 2005–2011（只上市） |")
    w("|---|---|---|")
    for tn in ("全部", "目的1", "目的3"):
        cells = []
        for sg in ("確認", "早年"):
            g = SG[(SG["問"] == "庫藏股") & (SG["類型"] == tn) & (SG["段"] == sg)]
            v = [f"{int(r.H)}日 {r.判定}" for r in g.itertuples() if isinstance(r.判定, str)]
            hit = [x for x in v if "測得出" in x]
            cells.append("；".join(hit) if hit else "五個視窗都測不出" if all("測不出" in x for x in v) else "；".join(v))
        w(f"| 庫藏股 {tn} 單筆（扣成本、對基準②） | {cells[0]} | {cells[1]} |")
    w(f"| 庫藏股組合層 挑中 {pk['格']}（10 檔） | {P(pk['確認']['年化中位'])}／{P(pk['確認']['回落中位'])} {pk['確認']['標籤']} | {P(pk['早年']['年化中位'])}／{P(pk['早年']['回落中位'])} {pk['早年']['標籤']} |")
    w(f"| 0050 | {P(Z['確認']['年化'])}／{P(Z['確認']['回落'])} | {P(Z['早年']['年化'])}／{P(Z['早年']['回落'])} |")
    w(f"| 臺灣50 剔除 單筆 | 依構造不可判定（每格 n ＜ 100） | —（無早年段） |")
    w(f"| 臺灣50 組合層 | {S['臺灣50 組合層']['判定']} | — |")
    w(f"\n組合層件標籤（兩段較嚴）：**{pk['件標籤（兩段較嚴）']}**。N：登錄 ＋2；臺灣50 組合層依構造不可判定、照登錄不計 ⇒ 實際 ＋1（庫藏股組合層）。\n")
    w("## 一、資料與窗\n")
    ji = S["接合"]
    w(f"- 庫藏股 treasury_buyback.csv（main b21882c9ff；sha256 核對：{S['閘']['事件檔 sha256']['庫藏股']}）：原始 {S['庫藏股原始']['件']:,} 件（決議日 {S['庫藏股原始']['決議日'][0]}～{S['庫藏股原始']['決議日'][1]}；上市 {S['庫藏股原始']['上市']:,}、上櫃 {S['庫藏股原始']['上櫃']:,}）；"
      f"合併 20 日後 全部 {S['庫藏股合併後']['全部']:,}、目的 1 {S['庫藏股合併後']['目的1']:,}、目的 3 {S['庫藏股合併後']['目的3']:,}、目的 2 {S['庫藏股合併後']['目的2（描述）']}（只描述）")
    w(f"- 臺灣50 tw50_changes.csv（資料庫線 0123 附件；sha256 核對：{S['閘']['事件檔 sha256']['臺灣50']}）：刪除 {S['臺灣50原始']['刪除']}、納入 {S['臺灣50原始']['納入']}（生效日 {S['臺灣50原始']['生效日'][0]}～{S['臺灣50原始']['生效日'][1]}）；2005～2008 照 seq259 不用；MSCI 臂刪除")
    w(f"- ⭐ 價量用**接合版面**：早年版面 950ad26e12（2004-02～2014-12，只上市）＋ main 快照 edc6f8002f（2015-01 起），還原因子接成一條（早年事件 × main 全部事件連乘）；"
      f"{ji['檔']:,} 檔（兩段都有 {ji['兩段都有']}、只早年 {ji['只早年']}、只 main {ji['只main']}）；閘：抽 20 檔跨界日還原比 ＝ 原始比（最大差 {S['閘']['跨界還原比＝原始比（抽 20 檔）']['最大差']:.1e}）")
    w("- 以前各件寫「兩版面還原尺度未接 ⇒ 做不到」；本件事件窗跨 2014／2015，照上式接（本線讀法，看事件數字前寫死）")
    w("- 母體（當月）：2012-06～2014-12 早年面板 W1、2015-08 起 panel_ext W1；2004～2012-05 沒有個股法人 ⇒ liq_ok ∧ bars_ok；2015-01～07 main 面板 bars 不足 ⇒ 用接合版面的有效 K 棒數補（詳 summary）。"
      "⚠ 2015 以前只有上市 ⇒ 早年段、探索段 2012～2014 都只含上市；⚠ W1 流動性門檻（近 20 日均額 ≥ 5,000 萬）剔掉大半庫藏股事件（多為中小型股），剔除計數見 summary")
    w("- 窗：庫藏股 早年 2005～2011（判）｜探索 2012～2018（描述、組合層挑格）｜確認 2019-01～2026-08-24（判）；臺灣50 探索 2009～2018｜確認 2019～2026-08-24")
    w("- 報酬 R_H ＝ 第 T＋H 日收盤（ffill）÷ T＋1 開盤 − 1（還原價）；停止交易／下市以最後有效收盤計（強制出場：開）；資料尾 T＋H 超過 2026-09-24 ⇒ 以末日收盤計（t1_censor 同讀法），筆數見表「尾截筆」")
    w("- 判定量 ＝ R_H − 基準②（同日、前 20 日報酬同十分位其他股 R_H 平均）− 0.585%；CI 以曆月分群；Bonferroni 按該段可判定格（n ≥ 100）：" + "、".join(f"{k} k＝{v}" for k, v in S["庫藏股可判定格數 k"].items()))
    w("- 視窗 5／10／20／60／120 日（協調者 09-28 指示；登錄 §九 列 4 值、10 日一併判；另欄報 4 值 k 下的判定）\n")
    w("## 二、問①庫藏股 單筆層\n")
    w("| 類型 | H | 段 | n | 扣成本後差 | Bonferroni CI | 判定 | 穩 | 4 值 k 判定 | 假訊號 p | 假也測得出 /1000 | 尾截 | 上櫃 |")
    w("|---|---|---|---|---|---|---|---|---|---|---|---|---|")
    st = lambda v: v if isinstance(v, str) else ""
    for r in SG[SG["問"] == "庫藏股"].to_dict("records"):
        if not r["n"]:
            w(f"| {r['類型']} | {r['H']} | {r['段']} | 0 | — | — | — | — | — | — | — | — | — |"); continue
        fp = "" if pd.isna(r["假訊號 p"]) else f"{r['假訊號 p']:.3f}"; fc = "" if pd.isna(r["假也測得出次數"]) else str(int(r["假也測得出次數"]))
        w(f"| {r['類型']} | {r['H']} | {r['段']} | {int(r['n'])} | {P(r['平均'])} | 〔{P(r['lo'])}, {P(r['hi'])}〕 | {r['判定']} | {st(r['穩'])} | {st(r['判定（4 視窗 k）'])} | "
          f"{fp} | {fc} | {int(r['尾截筆'])} | {int(r['上櫃筆'])} |")
    w("\n## 三、問②臺灣50 單筆層（全部依構造不可判定：每格 n ＜ 100；以下只描述，CI 為 95%）\n")
    w("| 類型 | H | 段 | n | 扣成本後差 | 95% CI | 假訊號 p |")
    w("|---|---|---|---|---|---|---|")
    for r in SG[SG["問"] == "臺灣50"].to_dict("records"):
        fp = "" if pd.isna(r["假訊號 p"]) else f"{r['假訊號 p']:.3f}"
        w(f"| {r['類型']} | {r['H']} | {r['段']} | {int(r['n'])} | {P(r['平均'])} | 〔{P(r['lo95'])}, {P(r['hi95'])}〕 | {fp} |")
    w(f"\n年均剔除事件：{ {k: round(v, 1) for k, v in S['臺灣50 組合層']['年均剔除事件'].items()} } ⇒ 組合層{S['臺灣50 組合層']['判定']}。\n")
    w("## 四、問①庫藏股 組合層（10 檔、抽籤、200 顆種子中位；對 0050 同段）\n")
    w("| 格 | 段 | 年化中位 | 回落中位 | 比值 | 標籤 | 種子合格比例 | 年均事件 | 平均投入 |")
    w("|---|---|---|---|---|---|---|---|---|")
    for r in PC.itertuples():
        w(f"| {r.類型}_H{r.H} | {r.段} | {P(r.年化中位)} | {P(r.回落中位)} | {r.比值:.2f} | {r.標籤} | {r.種子合格比例:.0%} | {r.年均事件:.1f} | {r.平均投入比例:.0%} |")
    w("\n0050：" + "；".join(f"{sg} {P(v['年化'])}／{P(v['回落'])}（比值 {v['比值']:.2f}）" for sg, v in Z.items()))
    w(f"\n挑格：退化排除（探索段年均事件 ＜ 10 或完全不持股）{pk['退化排除']}；探索段過判準 {pk['探索過判準格數']} 格 ⇒ 取比值最高 **{pk['格']}**。")
    fk = S["組合層假訊號（挑中格；同進場日同池隨機換股）"]
    w("假訊號（同進場日、同池隨機換股，200 次）：" + "；".join(f"{sg} p {v['p（隨機年化 ≥ 本格年化中位）']:.3f}（隨機年化中位 {P(v['隨機年化中位'])}）" for sg, v in fk.items()) + "\n")
    w("## 五、新規矩 ③ 出場敏感度（描述、不判）\n")
    sens = S.get("新規矩③ 出場敏感度（描述、不判；各段 [年化中位, 回落中位]）")
    if sens:
        w(sens["定義"] + f"；提前出場筆數 {sens['提前出場筆數']}\n")
        w("| 變體 | 早年 | 探索 | 確認 |")
        w("|---|---|---|---|")
        for k, v in sens.items():
            if k in ("定義", "提前出場筆數"):
                continue
            w(f"| {k} | " + " | ".join(f"{P(v[sg][0])}／{P(v[sg][1])}" for sg in ("早年", "探索", "確認")) + " |")
    else:
        w(S["新規矩③"])
    w("\n## 六、閘與查核\n")
    w(f"- 閘：事件檔 sha256 {S['閘']['事件檔 sha256']}；跨界還原比 {S['閘']['跨界還原比＝原始比（抽 20 檔）']}；挑中格種子 0 重跑權益逐位元相同 {S['閘']['挑中格種子0重跑權益逐位元相同']}")
    if CK:
        for k, v in CK.items():
            if isinstance(v, dict):
                w(f"- 獨立查核 {k}：{'過' if v['過'] else '⛔ 不過'}（" + "；".join(f"{a}={b}" for a, b in v.items() if a != "過") + "）")
        w(f"- 獨立查核 researchEvt_check.py（⛔ 不 import 主程式、avgdown、research13）：{'全部過' if CK.get('全部過') else '⛔ 有不過'}")
    w("")
    open(os.path.join(OUT, "REPORT.md"), "w", encoding="utf-8").write("\n".join(L))
    print("\n".join(L))


if __name__ == "__main__":
    main()
