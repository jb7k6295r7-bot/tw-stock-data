"""price_limit.py — 交易所的**漲跌停價**：唯一的一份實作（四點五）。
**純計算，不連外、不讀檔。**

## ⭐⭐ 為什麼要有這個檔：`LIMIT = 1.105` 寫死了一個**有年代的**數字

台股的單日漲跌幅限制 **2015-06-01 由 7% 放寬為 10%**。
⇒ 在那之前的事件日，成交價的合法區間是 `ref × [0.93, 1.07]`，⛔ 不是 `[0.90, 1.10]`。

⚠ 而這個錯的方向是**放行**（把 7% 的日子用 10% 去量 ⇒ 超出 7% 的那些靜靜通過）
⛔ ——不是誤報。⇒ 它不會有任何地方叫，只會讓 `factor_limit_check` 少抓。

⚠ 我方日線從 **2015-01-05** 開始 ⇒ 真正會走到 7% 那條路的只有 2015 上半年，
⛔ 但「只有五個月」不是不做的理由：`data/adj/` 的事件最早到 2008，
   而日線一旦往前回補，那條路就會變成十幾年。

## ⭐ 而漲跌停**不是** `ref × 1.1` 直接用，要落到**升降單位**上

```
漲停 = ref × (1+cap) **無條件捨去**到該價位的升降單位
跌停 = ref × (1−cap) **無條件進位**到該價位的升降單位
```
⚠ 升降單位是看**算出來的那個價**落在哪一檔，⛔ 不是看 `ref` 落在哪一檔
（`ref` 49.9 ⇒ 漲停 53.39 ⇒ 用 0.1 那一檔，不是 0.05）。

## 校準：官方 TWTAUU「股票減資恢復買賣參考價格」自己給的漲跌停

```
3040 遠見 2015-01-23  ref 41.28  →  漲停 44.15 ✅  跌停 38.40 ✅   （7% era）
3536 誠創 2015-03-20  ref 13.33  →  漲停 14.25 ✅  跌停 12.15 ⛔    （7% era）
2017 官田鋼 2015-12-30 ref  6.17  →  漲停  6.78 ✅  跌停  5.56 ✅   （10% era）
```
⇒ 六格裡**五格逐位相同**，⛔ 而 3536 那一格官方給 12.15、公式算 12.40（差 5 檔）。

## ⛔⛔ 而那一格**不是抄錯的**：我方那天的收盤就是 12.15

`data/stocks/3536.csv` 2015-03-20 的收盤 = **12.15** = 官方那一格。
⇒ 那天它**跌停鎖死**，而交易所用的跌停就是 12.15，⛔ 不是公式算的 12.40。
⇒ **證明**：我方的 `ref_price` 13.33 是對的（它本來就是官方那一欄），
  ⭐ 對不上的是**我的公式**——交易所那天的跌幅容許到 −8.85%。

⚠ **我不知道為什麼**，而「不知道」就寫不知道（三點6）——
⛔ 不要為了讓公式看起來完美而去改那個數字。

## ⛔⛔ 而 2026-09-13 的 `TWT49U` 給了第二個反例：**漲停與跌停的基準可以不同**

```
2353 宏碁 2015-01-05（含現金增資除權）
  除權息前收盤 21.35｜除權息參考價 21.02｜減除股利參考價 21.35｜開盤競價基準 21.35
  官方漲停 22.80 ＝ ⌊21.35 × 1.07⌋       ← ⭐ 用**減除股利參考價**
  官方跌停 19.55 ＝ ⌈21.02 × 0.93⌉       ← ⭐ 用**除權息參考價**
```
⇒ ⭐ 兩邊各用對自己**比較寬**的那個基準。
⚠ 所以「拿一個參考價 ± 一個百分比」這種算法，⛔ 結構上就不可能對到每一格。
⇒ 而這正是下面那個不對稱**不是我偷懶**的理由：官方自己就是不對稱的。

### ⇒ 落地：**收緊只做在有證據的那一側**

```
漲停側  官方三列 3/3 逐位相同  ⇒ ⭐ 用該日的 cap（7% or 10%）
跌停側  官方三列 2/3，有反例    ⇒ ⛔ **不收緊**，取「公式」與「10%」中較寬的那個
```
⚠ 這個不對稱是**故意的**，⛔ 不是忘了改：
在只有一個反例的時候，把閘門收到會誤報，等於把整道閘門變成噪音（六點五）。
⇒ 等 `TWTAUU` 的官方漲跌停欄回補下來（約 300 列），這一條就能用**官方的數字**
  重新判定，而不是靠我推公式。
"""
# ⭐ 放寬日：這一天（含）開始是 10%，之前是 7%。
WIDEN_DAY = "2015-06-01"
CAP_OLD = 0.07
CAP_NEW = 0.10

# (未滿這個價, 升降單位)；⛔ 以上皆為最後那一檔
TICKS = ((10.0, 0.01), (50.0, 0.05), (100.0, 0.1), (500.0, 0.5), (1000.0, 1.0))
TICK_BIG = 5.0


def cap(date):
    """→ 該日的單日漲跌幅上限（0.07 或 0.10）。`date` 是 `YYYY-MM-DD`。"""
    return CAP_NEW if str(date) >= WIDEN_DAY else CAP_OLD


# ⭐⭐ ETF／受益憑證的升降單位**跟股票不同**，⛔ 只有兩檔。
#   實測（TWT49U 官方逐筆給的漲跌停）：
#     00939 統一台灣高息動能 2026-01-02 ref 14.62 ⇒ 官方漲停 **16.08**
#     用股票的 0.05 去算會得到 16.05 ⇒ ⛔ 差一檔，而 16.08 不是 0.05 的倍數
#   ⚠ 而「16.05 vs 16.08」這種差在紙上看不出來，只有逐位比對才顯形。
TICKS_ETF = ((50.0, 0.01),)
TICK_ETF_BIG = 0.05

# ⭐ 官方在 `漲停價格／跌停價格` 兩欄用這兩個數字表示「**無漲跌幅限制**」。
#   實測：00714 群益道瓊美國地產 2020-01-16 ⇒ 漲停 `9,999.95`、跌停 `0.01`
UNLIMITED_UP = 9000.0
UNLIMITED_DOWN = 0.02


def tick(price, etf=False):
    """→ 這個價位的升降單位。

    ⛔ `etf` 一定要由呼叫端講清楚——⚠ 這一支**猜不出來**，
    而猜錯的表現是「差一檔」，在紙上跟對的一模一樣。
    """
    table = TICKS_ETF if etf else TICKS
    big = TICK_ETF_BIG if etf else TICK_BIG
    for hi, t in table:
        if price < hi:
            return t
    return big


def is_fine_tick(code):
    """→ 這個代號是不是「0.01 那一族」（ETF／受益證券／REIT）。

    ## ⛔ 這條規則是**量出來的**，不是照分類猜的

    拿官方 TWT49U 逐筆漲跌停當判準（2015~2016 共 1,453 筆）反推：

    ```
    ⭐ 0050／0051…      四位純數字，⛔ 但它是 ETF ⇒ 只看位數會漏
       01001T～01007T   不動產投資信託受益證券 ⇒ 0.01
    ⛔ 2002A            特別股（四位＋字母）⇒ **股票**檔位（官方 36.10，0.01 會給 36.09）
    ⛔ 910322／911609    TDR（六位）⇒ **股票**檔位（官方 29.10，0.01 會給 29.06）
    ```
    ⇒ 所以判準是「**開頭 00 或 01**」，⛔ 不是「不是四位純數字」
      ——⚠ 後者會把 TDR 與特別股一起拖下水，而那兩族實測是股票檔位。
    """
    c = str(code).strip()
    return c.startswith("00") or c.startswith("01")


# ⭐ 待接（2026-09-13 `site_inventory` 掃到，⛔ 還沒照 NEW_ENDPOINT 走過）：
#   TWSE  `/exchangeReport/TWT88U`「上市個股**首五日無漲跌幅**」
#   TPEx  `/zh-tw/mainboard/trading/info/no-limit.html` 上櫃首五日無漲跌幅
#   ⚠ 「新上市（櫃）前五個交易日無漲跌幅」這條規則我方是從 2015 上半年
#     148,484 組相鄰日對裡**量出來**的（8 組全部落在首五日）——⭐ 官方有名有姓。
#   ⇒ 接上之後，`factor_limit_check` 的母體判定就不必再靠那個推論。
#   ⛔ 而在接上之前**不要假設它有歷史**：同一家的 `tpex_spendi_history`
#     名字有 history、實際只有今年（CLAUDE.md 第二點⑤）。
def is_unlimited(limit_up, limit_down):
    """→ 官方這兩欄是不是在說「這一檔**無漲跌幅限制**」。

    ⭐ 這件事 `factor_limit_check.has_hard_limit()` 原本是**拿歷史推**的
    （非事件日 ≥ 500 天且從沒超過 10.5%）——⛔ 而官方**逐筆**就標著。
    ⚠ 推論那一版還有一個它處理不了的情形：**同一檔在不同時期可以換**
      （加掛、改型態）⇒ 一檔一個布林值本來就不夠。
    """
    up, dn = _num(limit_up), _num(limit_down)
    if up is None or dn is None:
        return False
    return up >= UNLIMITED_UP or dn <= UNLIMITED_DOWN


def _num(x):
    try:
        return float(str(x).replace(",", "").strip())
    except (TypeError, ValueError):
        return None


def _cents(x):
    return x * 100.0


def _round_to_tick(value, down, etf=False):
    """把 `value` 落到升降單位上；`down=True` 捨去、`False` 進位。

    ⛔ 用「分」當整數算——浮點直接除會在剛好落在檔位上的時候兩邊跳。
    """
    t = _cents(tick(value, etf))
    v = _cents(value)
    n = (v + 1e-6) // t if down else -((-v + 1e-6) // t)
    return round(n * t) / 100.0


def up(ref, date, etf=False):
    """→ 該日的漲停價。⛔ `etf` 要由呼叫端講（升降單位不同）。"""
    return _round_to_tick(ref * (1.0 + cap(date)), True, etf)


def down(ref, date, etf=False):
    """→ 該日的跌停價。⛔ `etf` 要由呼叫端講（升降單位不同）。"""
    return _round_to_tick(ref * (1.0 - cap(date)), False, etf)


def down_observed(ref, date, etf=False):
    """→ 跌停價，但**取較寬的那一個**（⛔ 有已知反例，見檔頭）。

    ⚠ 這一支跟 `down()` **不是重複實作**：
    `down()` 是「公式說的跌停」——拿去跟官方欄位逐位比對的那個；
    這一支是「⛔ 我敢拿去當閘門的跌停」——在有反例的那一側不收緊。
    """
    return min(down(ref, date, etf),
               _round_to_tick(ref * (1.0 - CAP_NEW), False, etf))


def within(price, ref, date, slack=0.0, etf=False):
    """→ 這個成交價在不在該日的漲跌停之內（⭐ 閘門用的那一版）。

    `slack` 是**相對**餘裕（⛔ 不是絕對值——三點6：兩者長得一樣而結論相反）。
    ⚠ 跌停側走 `down_observed()`，⛔ 不是 `down()`——理由見檔頭那一節。
    """
    if not ref or ref <= 0:
        return True
    return (down_observed(ref, date, etf) * (1.0 - slack) <= price
            <= up(ref, date, etf) * (1.0 + slack))

